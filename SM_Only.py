def normalize_global(train, val, test):
    mean = np.mean(train)
    std = np.std(train) + 1e-8
    train_n = (train - mean) / std
    val_n   = (val - mean) / std
    test_n  = (test - mean) / std
    return train_n, val_n, test_n, mean, std
def normalize_static(static_dict):
    norm_static = {}
    stats = {}
    for key, data in static_dict.items():
        mean = np.mean(data)
        std = np.std(data) + 1e-8

        norm_static[key] = (data - mean) / std
        stats[key] = {"mean": float(mean), "std": float(std)}
    return norm_static, stats
