def stack_invariant_with_variant(X_variant, invariant_dict):
    N, T, H, W, C_v = X_variant.shape
    # Stack invariant layers â†’ (H, W, C_i)
    invariant_stack = np.stack(list(invariant_dict.values()), axis=-1)
    # Expand â†’ (1,1,H,W,C_i)
    invariant_stack = invariant_stack[np.newaxis, np.newaxis, ...]
    # Repeat across samples â†’ (N,1,H,W,C_i)
    invariant_stack = np.repeat(invariant_stack, N, axis=0)
    # Concatenate along channel dimension
    X_combined = np.concatenate([X_variant, invariant_stack], axis=-1)
    return X_combined
