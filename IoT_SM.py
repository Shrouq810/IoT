# SM BRANCH (PRETRAINED SURROGATE)
# =============================================================================
def build_sm_branch(input_shape):
    inputs = Input(shape=input_shape, name="sm_input")
    x = ConvLSTM2D(8, (3, 3), padding="same", return_sequences=True, name="sm_lstm1")(inputs)
    x = Dropout(0.2, name="sm_dropout1")(x)
    x = LayerNormalization(name="sm_ln1")(x)
    x = ConvLSTM2D(42, (3, 3), padding="same", return_sequences=False, name="sm_lstm2")(x)
    x = Dropout(0.2, name="sm_dropout2")(x)
    x = LayerNormalization(name="sm_ln2")(x)
    outputs = Conv2D(1, (1, 1), activation="linear", padding="same", name="sm_head")(x)
    return Model(inputs=inputs, outputs=outputs, name="SM_Branch")
# =============================================================================
# IOT BRANCH (LEARNED FROM SCRATCH)
# =============================================================================
def build_iot_branch(input_shape):
    inputs = Input(shape=input_shape, name="iot_input")

    x = ConvLSTM2D(8, (3, 3), padding="same", return_sequences=True, name="iot_lstm1")(inputs)
    x = Dropout(0.2, name="iot_dropout1")(x)
    x = LayerNormalization(name="iot_ln1")(x)

    x = ConvLSTM2D(42, (3, 3), padding="same", return_sequences=False, name="iot_lstm2")(x)
    x = Dropout(0.2, name="iot_dropout2")(x)
    x = LayerNormalization(name="iot_ln2")(x)

    outputs = Conv2D(1, (1, 1), activation="linear", padding="same", name="iot_head")(x)

    return Model(inputs=inputs, outputs=outputs, name="IoT_Branch")
# =============================================================================
# FUSION MODEL (TRANSFER LEARNING)
# =============================================================================
def build_sm_iot_fusion_model(sm_input_shape,
                             iot_input_shape,
                             pretrained_sm_path=None,
                             freeze_sm=False):

    # --- build branches ---
    sm_branch = build_sm_branch(sm_input_shape)
    iot_branch = build_iot_branch(iot_input_shape)

    # --- transfer learning: load pretrained SM ---
    if pretrained_sm_path is not None and os.path.exists(pretrained_sm_path):
        sm_branch.load_weights(pretrained_sm_path)
 
        if freeze_sm:
            for layer in sm_branch.layers:
                layer.trainable = False
        
        else:
            print("[INFO] SM branch fine-tuned (recommended)")

    else:
        print("[WARNING] No pretrained SM weights â†’ training from scratch")
    # --- inputs ---
    sm_input = Input(shape=sm_input_shape, name="sm_input")
    iot_input = Input(shape=iot_input_shape, name="iot_input")
    # --- forward ---
    sm_pred = sm_branch(sm_input)
    iot_pred = iot_branch(iot_input)
    # --- fusion ---
    fused = Concatenate(axis=-1, name="fusion_concat")([sm_pred, iot_pred])
    final_output = Conv2D(
        1,
        (1, 1),
        activation="linear",
        padding="same",
        name="fusion_head"
    )(fused)
    model = Model(
        inputs=[sm_input, iot_input],
        outputs=final_output,
        name="SM_IoT_TransferLearning_Model"
    )
    return model
