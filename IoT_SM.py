def stack_invariant_with_variant(x_variant, invariant_dict):
    """
    Concatenate invariant (static) spatial layers to variant (dynamic) inputs.

    x_variant shape: (N, T, H, W, C_v)
    invariant_dict: {name: (H, W)}
    returns: (N, T, H, W, C_v + C_i)
    """
    n, t, h, w, _ = x_variant.shape
    invariant_stack = np.stack(list(invariant_dict.values()), axis=-1)   # (H, W, C_i)
    invariant_stack = invariant_stack[np.newaxis, np.newaxis, ...]       # (1, 1, H, W, C_i)
    invariant_stack = np.repeat(invariant_stack, n, axis=0)              # (N, 1, H, W, C_i)
    return np.concatenate([x_variant, invariant_stack], axis=-1).astype(np.float32)
