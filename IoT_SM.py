def normalize_global(train, val, test):
    mean = np.mean(train)
    std = np.std(train) + 1e-8
    train_n = (train - mean) / std
    val_n = (val - mean) / std
    test_n = (test - mean) / std

    return train_n.astype(np.float32), val_n.astype(np.float32), test_n.astype(np.float32), mean, std
def normalize_static(static_dict):
    """
    Normalize each invariant layer independently.
    """
    static_norm = {}
    static_stats = {}

    for key, data in static_dict.items():
        mean = np.mean(data)
        std = np.std(data) + 1e-8
        static_norm[key] = ((data - mean) / std).astype(np.float32)
        static_stats[key] = {"mean": float(mean), "std": float(std)}
    return static_norm, static_stats
