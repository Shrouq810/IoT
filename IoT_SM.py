def read_and_process_static_data(file_path):
    with rasterio.open(file_path) as src:
        data = src.read(1)
        nodata = src.nodata
        if nodata is not None:
            data[data == nodata] = 0
    return data
def process_static_input(base_path, file_name):
    file_path = os.path.join(base_path, file_name)
    return read_and_process_static_data(file_path)
def crop_to_domain(data, shape=(744, 645)):
    h, w = shape
    return data[:h, :w]
