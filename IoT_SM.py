def load_common_times(dirpath):
    xlsx = glob.glob(os.path.join(dirpath, "Times.xlsx"))
    if xlsx:
        p = xlsx[0]
        return (
            pd.read_excel(p, sheet_name="Train")["Date"].astype(str).tolist(),
            pd.read_excel(p, sheet_name="Val")["Date"].astype(str).tolist(),
            pd.read_excel(p, sheet_name="Test")["Date"].astype(str).tolist(),
        )

    jsn = glob.glob(os.path.join(dirpath, "common_times.json"))
    if jsn:
        with open(jsn[0], "r") as f:
            d = json.load(f)
        return d["train"], d["val"], d["test"]

    npz = glob.glob(os.path.join(dirpath, "common_times.npz"))
    if npz:
        z = np.load(npz[0], allow_pickle=True)
        return z["train"].tolist(), z["val"].tolist(), z["test"].tolist()
    raise FileNotFoundError("Times.xlsx, common_times.json, or common_times.npz not found.")
def load_array(dirpath, stem):
    npz_path = os.path.join(dirpath, f"{stem}.npz")
    npy_path = os.path.join(dirpath, f"{stem}.npy")
    if os.path.exists(npz_path):
        z = np.load(npz_path, allow_pickle=True)
        if "arr" in z.files:
            return z["arr"]
        return z[z.files[0]]
    if os.path.exists(npy_path):
        return np.load(npy_path, allow_pickle=True)
    raise FileNotFoundError(f"Missing array file for: {stem}")
def fix_y(y):
    """
    Ensure Y shape is (N, H, W, 1)
    """
    y = np.array(y)
    if y.ndim == 4 and y.shape[1] == 1:
        y = np.squeeze(y, axis=1)
        y = y[..., np.newaxis]
    elif y.ndim == 3:
        y = y[..., np.newaxis]
    return y.astype(np.float32)
