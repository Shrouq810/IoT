# SIMPLE MASKED MSE LOSS 
# =============================================================================
class SimpleMaskedMSE(tf.keras.losses.Loss):
    """
    Mean Squared Error computed only within the FEMA floodplain mask.
    """
    def __init__(self, mask, **kwargs):
        super().__init__(**kwargs)
        self.mask = tf.cast(mask > 0, tf.float32)

    def call(self, y_true, y_pred):

        if y_true.shape.rank == 4:
            y_true = tf.squeeze(y_true, axis=-1)
        if y_pred.shape.rank == 4:
            y_pred = tf.squeeze(y_pred, axis=-1)

        err = tf.square(y_true - y_pred)

        mask = tf.expand_dims(self.mask, axis=0)
        mask = tf.broadcast_to(mask, tf.shape(err))

        return tf.reduce_sum(err * mask) / (
            tf.reduce_sum(mask) + tf.keras.backend.epsilon()
        )
